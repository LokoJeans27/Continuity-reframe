"""Local semantic camera brief. No image generation, network, geometry or GPU work."""
PRESETS={'frontal':(0,0,1.0),'three_quarter':(45,0,1.0),'lateral':(90,0,1.0),'overhead':(0,90,1.0),'low':(0,-30,1.0),'rear':(180,0,1.0),'wide':(0,0,1.8)}

class H3ManualCameraBrief:
    @classmethod
    def INPUT_TYPES(cls):
        return {'required':{
            'base_prompt':('STRING',{'multiline':True,'default':''}),
            'use_angle_brief':('BOOLEAN',{'default':False}),
            'preset':(['custom']+list(PRESETS),),
            'azimuth':('FLOAT',{'default':45.0,'min':-180.0,'max':180.0,'step':1.0,'display':'slider'}),
            'elevation':('FLOAT',{'default':0.0,'min':-60.0,'max':90.0,'step':1.0,'display':'slider'}),
            'distance':('FLOAT',{'default':1.0,'min':0.5,'max':3.0,'step':0.05,'display':'slider'}),
            'notes':('STRING',{'multiline':True,'default':''}),
            'guide_reviewed_for_this_camera':('BOOLEAN',{'default':False})}}
    RETURN_TYPES=('STRING',);RETURN_NAMES=('camera_prompt',)
    FUNCTION='make';CATEGORY='H3 / Manual Camera';OUTPUT_NODE=True

    def make(self,base_prompt,use_angle_brief,preset,azimuth,elevation,distance,notes,guide_reviewed_for_this_camera):
        if not use_angle_brief:
            return {'ui':{'text':[base_prompt]},'result':(base_prompt,)}
        if not guide_reviewed_for_this_camera:
            raise ValueError('Create/review a manual guide matching this camera intention before H3 execution. No image is generated by this node.')
        if preset!='custom':
            if preset not in PRESETS:raise ValueError('Unknown camera preset')
            azimuth,elevation,distance=PRESETS[preset]
        if not (-180<=azimuth<=180 and -60<=elevation<=90 and .5<=distance<=3):raise ValueError('Camera control outside supported brief range')
        brief=(f'Manual target-camera intention: azimuth {azimuth:g} degrees, elevation {elevation:g} degrees, relative distance {distance:g}. '
               'Azimuth 0 means front, +90 means the performer right side, 180 means rear; positive elevation looks down. '
               'Distance is an editorial framing cue, not measured geometry or focal length. '
               'Interpret these values approximately through the manually reviewed guide. '
               'Decide visibility first; do not move out-of-frame objects into view. Keep source initial posture and the full gesture margin.')
        if notes.strip():brief+='\n'+notes.strip()
        prompt=base_prompt+'\n\n'+brief
        return {'ui':{'text':[prompt]},'result':(prompt,)}

NODE_CLASS_MAPPINGS={'H3ManualCameraBrief':H3ManualCameraBrief}
NODE_DISPLAY_NAME_MAPPINGS={'H3ManualCameraBrief':'Manual Camera Brief (no image generation)'}
